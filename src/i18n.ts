const storageKey = "portfolio-analyze.language";
let initialLanguage = navigator.language.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
try {
  const saved = localStorage.getItem(storageKey);
  if (saved === "en" || saved === "zh-CN") initialLanguage = saved;
} catch {
  // Language switching remains available when browser storage is disabled.
}

function syncLanguage(language: string) {
  document.documentElement.lang = language;
  try {
    localStorage.setItem(storageKey, language);
  } catch {
    // Persistence is optional in restricted browser contexts.
  }
}

i18n.on("languageChanged", syncLanguage);
void i18n.use(initReactI18next).init({
  lng: initialLanguage,
  fallbackLng: "en",
  supportedLngs: ["en", "zh-CN"],
  resources: { en: { translation: en }, "zh-CN": { translation: zh } },
  keySeparator: false,
  interpolation: { escapeValue: false },
});

export function formatDate(value: string | null | undefined, short = false) {
  if (!value) return "—";
  const date = new Date(value.length === 10 ? `${value}T00:00:00` : value);
  if (Number.isNaN(date.getTime())) return value;
  return date.toLocaleDateString(i18n.resolvedLanguage === "zh-CN" ? "zh-CN" : "en-US", {
    ...(short ? {} : { year: "numeric" as const }),
    month: "short",
    day: "numeric",
  });
}

